"""
Metric Provenance Module for NetSlice.
Provides standard metadata, taxonomy, and schemas for all network telemetry:
- MEASURED: Directly observed from physical OS counters, socket connections, or live RTT handshakes.
- ESTIMATED: Calculated via documented heuristics (e.g. process inspection mapping, probe-derived latency).
- SIMULATED: Generated by synthetic traffic generator or token bucket rate limiter model.
- UNAVAILABLE: Cannot be measured reliably in the current environment (e.g. TLS encrypted payloads, idle state).
"""

import time
from typing import Any, Dict, Optional

class MetricProvenanceStatus:
    MEASURED = "MEASURED"
    ESTIMATED = "ESTIMATED"
    SIMULATED = "SIMULATED"
    UNAVAILABLE = "UNAVAILABLE"

def create_provenance_metric(
    value: Any,
    unit: str,
    source: str,
    status: str,
    description: str,
    measured_at: Optional[float] = None
) -> Dict[str, Any]:
    """Builds a standardized metric object with explicit provenance metadata."""
    return {
        "value": value,
        "unit": unit,
        "source": source,
        "status": status,
        "measured_at": measured_at or time.time(),
        "description": description
    }
